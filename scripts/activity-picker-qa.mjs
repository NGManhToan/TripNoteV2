import { mkdir, writeFile } from "node:fs/promises";

const output = new URL("../artifacts/qa/", import.meta.url);
await mkdir(output, { recursive: true });
const page = await fetch("http://127.0.0.1:9231/json/new?about:blank", { method: "PUT" }).then((response) => response.json());
const socket = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((resolve, reject) => { socket.addEventListener("open", resolve, { once: true }); socket.addEventListener("error", reject, { once: true }); });
let nextId = 0;
const pending = new Map();
socket.addEventListener("message", ({ data }) => { const message = JSON.parse(data); const resolve = pending.get(message.id); if (resolve) { pending.delete(message.id); resolve(message); } });
const command = (method, params = {}) => new Promise((resolve, reject) => { const id = ++nextId; pending.set(id, (message) => message.error ? reject(new Error(message.error.message)) : resolve(message.result)); socket.send(JSON.stringify({ id, method, params })); });
const evaluate = async (expression) => { const result = await command("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true }); if (result.exceptionDetails) throw new Error(result.exceptionDetails.text); return result.result.value; };
const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const screenshot = async (name) => { const shot = await command("Page.captureScreenshot", { format: "png", captureBeyondViewport: false }); await writeFile(new URL(name, output), Buffer.from(shot.data, "base64")); };
const clickButton = async (label) => {
  const found = await evaluate(`(()=>{const button=[...document.querySelectorAll('button')].find(item=>item.innerText.includes(${JSON.stringify(label)}));if(!button)return false;button.click();return true})()`);
  if (!found) throw new Error(`Missing button: ${label}`);
};
await command("Page.enable");
await command("Emulation.setDeviceMetricsOverride", { width: 414, height: 906, deviceScaleFactor: 1, mobile: true });
await command("Page.navigate", { url: "http://127.0.0.1:5174/home/trip/sample-dalat" });
await wait(800);
await evaluate("document.querySelector('button[aria-label=\"Thêm hoạt động\"]')?.click()");
await wait(250);
if (!(await evaluate("document.body.innerText.includes('Chọn loại hoạt động')"))) throw new Error("Default activity types did not open.");
await clickButton("Khác");
await wait(250);
if (!(await evaluate("document.body.innerText.includes('Loại hoạt động tùy chỉnh')"))) throw new Error("Custom types list did not open.");
await screenshot("activity-custom-types-414x906.png");
await clickButton("Tạo loại mới");
await wait(200);
const setType = await evaluate("(()=>{const input=document.querySelector('input[placeholder=\"Ví dụ: Chụp ảnh\"]');if(!input)return false;const setter=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set;setter.call(input,'Chụp ảnh');input.dispatchEvent(new Event('input',{bubbles:true}));input.dispatchEvent(new Event('change',{bubbles:true}));return true})()");
if (!setType) throw new Error("Custom type form did not open.");
await evaluate("document.querySelector('form')?.requestSubmit()");
await wait(350);
const customType = JSON.parse(await evaluate("JSON.stringify(JSON.parse(localStorage.getItem('tripnote-v2-activity-types')||'[]').find(item=>item.name==='Chụp ảnh')||null)"));
if (!customType) throw new Error("New activity type was not persisted.");
const setActivity = await evaluate("(()=>{const form=document.querySelector('form');const inputs=[...form.querySelectorAll('input')];const name=inputs.find(input=>input.placeholder.includes('Tham quan hồ'));const planned=inputs.find(input=>input.placeholder==='0');const actual=inputs.find(input=>input.placeholder==='Chưa ghi nhận');if(!name||!planned||!actual)return false;const setter=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set;for(const [input,value] of [[name,'Hoạt động kiểm thử loại mới'],[planned,'2000'],[actual,'1500']]){setter.call(input,value);input.dispatchEvent(new Event('input',{bubbles:true}));input.dispatchEvent(new Event('change',{bubbles:true}));}return true})()");
if (!setActivity) throw new Error("Activity form did not open after type creation.");
await evaluate("document.querySelector('form')?.requestSubmit()");
await wait(700);
const saved = JSON.parse(await evaluate("JSON.stringify(JSON.parse(localStorage.getItem('tripnote-v2-trips')||'[]').find(trip=>trip.id==='sample-dalat')?.itinerary.flatMap(day=>day.activities).find(activity=>activity.name==='Hoạt động kiểm thử loại mới')||null)"));
if (!saved || saved.category !== "Chụp ảnh" || saved.customTypeId !== customType.id || saved.actualCost !== 1500) throw new Error("Activity values/type were not saved correctly.");
await command("Page.reload");
await wait(600);
await evaluate("document.querySelector('button[aria-label=\"Thêm hoạt động\"]')?.click()");
await wait(180);
await clickButton("Khác");
await wait(180);
const afterReload = await evaluate("document.body.innerText.includes('Chụp ảnh')");
if (!afterReload) throw new Error("Custom type was missing after reload.");
await evaluate("import('/src/features/trips/data.ts').then(({sampleTrips})=>localStorage.setItem('tripnote-v2-trips',JSON.stringify(sampleTrips)));localStorage.removeItem('tripnote-v2-activity-types')");
const result = { sheetOpened: true, customType, savedActivity: saved, survivesReload: afterReload };
await writeFile(new URL("activity-picker-qa.json", output), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
socket.close();
